#!/usr/bin/env bash
set -euo pipefail

echo ""
echo " ============================================="
echo "  Law RAG  |  Setup"
echo " ============================================="
echo ""

# ── 1. Check Docker ────────────────────────────────────────────────────────────
if ! docker info > /dev/null 2>&1; then
    echo " ERROR: Docker Desktop is not running."
    echo ""
    echo " Please open Docker Desktop, wait for it to finish starting,"
    echo " then run this script again."
    exit 1
fi
echo " [OK] Docker is running"

# ── 2. Create .env if it does not exist ────────────────────────────────────────
if [ -f .env ]; then
    echo " [OK] .env found — using existing configuration"
else
    echo ""
    echo " Let's configure your installation."
    echo " You will need an OpenAI API key."
    echo " Get one at: https://platform.openai.com/api-keys"
    echo ""

    while true; do
        read -rp " OpenAI API key (starts with sk-): " OPENAI_KEY
        [ -n "$OPENAI_KEY" ] && break
        echo " A key is required — please try again."
    done

    echo ""
    read -rp " Admin login email  [admin@lawfirm.local]: " ADMIN_EMAIL
    ADMIN_EMAIL="${ADMIN_EMAIL:-admin@lawfirm.local}"

    read -rp " Admin password     [changeme]: " ADMIN_PASSWORD
    ADMIN_PASSWORD="${ADMIN_PASSWORD:-changeme}"

    SECRET_KEY=$(openssl rand -base64 32)
    # hex, not base64 — this password is embedded directly in the Postgres
    # connection URL, and base64's `/`, `+`, `=` would corrupt URL parsing
    POSTGRES_PASSWORD=$(openssl rand -hex 24)

    cat > .env <<EOF
# Law RAG — Configuration
# Generated by setup.sh. Keep this file private.

OPENAI_API_KEY=${OPENAI_KEY}
SECRET_KEY=${SECRET_KEY}
ADMIN_EMAIL=${ADMIN_EMAIL}
ADMIN_PASSWORD=${ADMIN_PASSWORD}
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
EOF

    echo ""
    echo " [OK] Configuration saved to .env"
fi

# ── 3. Build and start ─────────────────────────────────────────────────────────
echo ""
echo " Starting Law RAG..."
echo " (First launch builds Docker images — this takes a few minutes)"
echo ""
docker compose up -d --build

# ── 4. Wait for healthy ────────────────────────────────────────────────────────
echo ""
echo " Waiting for the app to be ready..."
until curl -sf http://localhost:8000/health > /dev/null 2>&1; do
    sleep 3
done

# ── 5. Done ────────────────────────────────────────────────────────────────────
DISPLAY_EMAIL=$(grep "^ADMIN_EMAIL=" .env | cut -d= -f2)
DISPLAY_PASS=$(grep "^ADMIN_PASSWORD=" .env | cut -d= -f2)

echo ""
echo " ============================================="
echo "  Law RAG is ready!"
echo ""
echo "  Open in your browser: http://localhost:5173"
echo "  Email:    ${DISPLAY_EMAIL}"
echo "  Password: ${DISPLAY_PASS}"
echo " ============================================="
echo ""

# Open browser (Mac or Linux)
if command -v open > /dev/null 2>&1; then
    open http://localhost:5173
elif command -v xdg-open > /dev/null 2>&1; then
    xdg-open http://localhost:5173
fi
